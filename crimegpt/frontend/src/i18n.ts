// Restore the officer's last choice. Without this every reload silently reverted
// to English — and because document generation sends `i18n.language` as the output
// language, a "generate" after a reload quietly produced an English document for an
// officer who had selected Gujarati.
const SUPPORTED = ['en', 'hi', 'gu'];
const savedLang = (() => {
  try {
    const stored = localStorage.getItem('lang');
    return stored && SUPPORTED.includes(stored) ? stored : 'en';
  } catch {
    return 'en';   // private mode / storage disabled
  }
})();

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: savedLang,
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false
    }
  });

i18n.on('languageChanged', (lng) => {
  try {
    localStorage.setItem('lang', lng);
  } catch {
    /* storage unavailable — the session still works, it just won't persist */
  }
});

// Keep <html lang> in step with the active locale. Without this the document
// stays lang="en" while showing Devanagari or Gujarati, so screen readers
// announce that text with English pronunciation rules.
const syncDocumentLang = (lng: string) => {
  document.documentElement.lang = lng;
};
syncDocumentLang(i18n.language);
i18n.on('languageChanged', syncDocumentLang);

export default i18n;
